// build/version/index.js

/**
 * Build version distributor.
 *
 * `build/version/version.json` is the single source of truth of the website
 * version. This script distributes it to every place that needs it:
 *
 *   1. `src/version.mjs` -> generated module imported by the website bundle.
 *   2. `public/*.html`   -> `?v=` query string of the static assets.
 *
 * The generated module is the only place the browser bundle reads the version
 * from, so bumping the version here invalidates every cached asset at once.
 *
 * Usage:
 *   node ./build/version          # distribute the current version
 *   node ./build/version --bump   # increment the version, then distribute
 *   VERSION_BUMP=1 node ./build/version
 */

const fs = require('fs');
const path = require('path');

/** Repository root. */
const root = path.join(__dirname, '../..');

/** File that stores the current version. */
const versionFile = path.join(__dirname, 'version.json');

/** Module generated from the version. */
const outputFile = path.join(root, 'src/version.mjs');

/** Folder scanned for the static HTML files. */
const publicDir = path.join(root, 'public');

/**
 * Reads the version stored in `version.json`.
 *
 * @returns {number} The current version.
 * @throws {Error} When the file does not contain a valid version.
 */
function readVersion() {
  const raw = JSON.parse(fs.readFileSync(versionFile, 'utf8'));
  const version = raw === null || typeof raw !== 'object' ? NaN : Number(raw.version);

  if (!Number.isInteger(version) || version < 0) {
    throw new Error(`Invalid "version" in ${path.relative(root, versionFile)}.`);
  }

  return version;
}

/**
 * Writes the version back to `version.json`.
 *
 * @param {number} version - Version to persist.
 * @returns {void}
 */
function writeVersion(version) {
  fs.writeFileSync(versionFile, `${JSON.stringify({ version }, null, 2)}\n`, 'utf8');
}

/**
 * Builds the content of `src/version.mjs`.
 *
 * @param {number} version - Current version.
 * @returns {string} The module source.
 */
function renderModule(version) {
  return [
    '/**',
    ' * @file Build version.',
    ' *',
    ' * This file is generated by `build/version/index.js` from',
    ' * `build/version/version.json`. Do not edit it manually, run',
    ' * `npm run update-version` instead.',
    ' *',
    ' * @module version',
    ' */',
    '',
    '/** Numeric build version. */',
    `export const version = ${version};`,
    '',
    '/** Cache-busting query string appended to static asset requests. */',
    `export const fileVersion = '?v=${version}';`,
    '',
    '/** Name of the Cache Storage bucket used by the service worker. */',
    "export const cacheName = 'pony-driland-v1';",
    '',
  ].join('\n');
}

/**
 * Rewrites the `?v=` query string of every static HTML file.
 *
 * @param {number} version - Current version.
 * @returns {string[]} The files that were changed.
 */
function updateHtmlFiles(version) {
  /** @type {string[]} */
  const updated = [];

  for (const name of fs.readdirSync(publicDir)) {
    if (!name.endsWith('.html')) continue;

    const file = path.join(publicDir, name);
    const raw = fs.readFileSync(file, 'utf8');
    const next = raw.replace(/(\?v=)\d+/g, `$1${version}`);

    if (next === raw) continue;

    fs.writeFileSync(file, next, 'utf8');
    updated.push(path.relative(root, file));
  }

  return updated;
}

/**
 * Distributes the version to every generated file.
 *
 * @returns {void}
 */
function main() {
  const bump = process.argv.includes('--bump') || process.env.VERSION_BUMP === '1';
  const version = readVersion() + (bump ? 1 : 0);

  if (bump) writeVersion(version);

  fs.writeFileSync(outputFile, renderModule(version), 'utf8');
  console.log(`🏷  Version: ${version} -> ${path.relative(root, outputFile)}`);

  for (const file of updateHtmlFiles(version)) {
    console.log(`🏷  Version: ${version} -> ${file}`);
  }
}

main();
